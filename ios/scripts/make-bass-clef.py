#!/usr/bin/env python3
"""Turn scripts/bass-clef.svg into Views/BassClef.swift (#72).

The bass clef is drawn, like the treble clef (make-treble-clef.py), so nothing
depends on a font on the phone. Its source is Bravura's F clef, whose outline
is in bass-clef.svg in font units.

PLACEMENT IS MEASURED. An F clef is only an F clef if its two dots sit either
side of the F3 line. In the source they are centred at y = 700 and 500 font
units, so the F line is 600 and a staff space is 200 units. The app's staff
space is 20, so the scale is 0.1, flipped because font y runs up. The bass
staff keeps the treble staff's five lines (y = 60 to 140) and F3 is its second
line, y = 80. The left edge sits at x = 36, beside where the treble clef
starts (34). index.html carries the same transform; change one and change the
other.

    python3 ios/scripts/make-bass-clef.py            write the Swift
    python3 ios/scripts/make-bass-clef.py --check    fail if it is stale
"""
import re, sys, pathlib

HERE = pathlib.Path(__file__).resolve().parent
SVG = HERE / "bass-clef.svg"
OUT = HERE.parent / "Mellophone" / "Views" / "BassClef.swift"

SPACE_UNITS = 200.0   # dot centre to dot centre, measured in the source
F_LINE_UNITS = 600.0  # midway between the dots
GLYPH_LEFT = -4.0     # the source bbox's left edge
SCALE = 20.0 / SPACE_UNITS
F_LINE = 80.0
LEFT_EDGE = 36.0
TX = LEFT_EDGE - GLYPH_LEFT * SCALE
TY = F_LINE + F_LINE_UNITS * SCALE   # y' = TY - y * SCALE

NUM = re.compile(r'-?\d+(?:\.\d+)?')


def pt(x, y):
    return "CGPoint(x: %.2f, y: %.2f)" % (x * SCALE + TX, TY - y * SCALE)


def to_swift(d):
    lines = []
    for cmd, args in re.findall(r'([MLCZ])([^MLCZ]*)', d):
        n = [float(v) for v in NUM.findall(args)]
        if cmd == "M":
            lines.append("        p.move(to: %s)" % pt(n[0], n[1]))
        elif cmd == "L":
            lines.append("        p.addLine(to: %s)" % pt(n[0], n[1]))
        elif cmd == "C":
            lines.append("        p.addCurve(to: %s, control1: %s, control2: %s)"
                         % (pt(n[4], n[5]), pt(n[0], n[1]), pt(n[2], n[3])))
        elif cmd == "Z":
            lines.append("        p.closeSubpath()")
    return lines


def main():
    d = re.search(r'<path d="([^"]*)"', SVG.read_text()).group(1)
    body = "\n".join(to_swift(d))
    swift = '''// GENERATED by ios/scripts/make-bass-clef.py. Do not edit by hand.
//
// Source: the F clef of Bravura (Steinberg, SIL Open Font License 1.1), its
// outline kept at ios/scripts/bass-clef.svg. index.html draws the same path
// with transform="translate(%.2f %.2f) scale(%.2f %.2f)".
//
// Placement, measured: the clef's dots are a staff space apart either side of
// the F line, so their midpoint is put on F3, the bass staff's second line at
// y = 80 (#72).

import SwiftUI

enum BassClef {
    static let path: Path = {
        var p = Path()
%s
        return p
    }()
}
''' % (TX, TY, SCALE, -SCALE, body)
    if "--check" in sys.argv:
        if OUT.read_text() != swift:
            sys.exit("BassClef.swift is stale: run python3 ios/scripts/make-bass-clef.py")
        print("OK: BassClef.swift matches bass-clef.svg")
        return
    OUT.write_text(swift)
    print("wrote %s, transform translate(%.2f %.2f) scale(%.2f %.2f)" % (OUT.relative_to(HERE.parent.parent), TX, TY, SCALE, -SCALE))


if __name__ == "__main__":
    main()
