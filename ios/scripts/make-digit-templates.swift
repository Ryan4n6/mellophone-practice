// Generates Mellophone/Import/RasterDigitTemplates.swift (#49): the digits of
// every SIL Open Font License font MuseScore 4 installs, the engraved time
// signature and tuplet digits of its music fonts and the plain digits of its
// text fonts, each squashed to the grid DigitReader compares against. Only the
// numbers are kept; no font goes in the app.
//
// Baked in rather than drawn from the phone's own fonts at run time: the
// simulator and the Mac carry different faces, and a reader whose digits
// depend on which fonts a device has read PEAK's bar counts one way in a test
// and another way on the bench.
//
//   swiftc -O -o /tmp/make-digit-templates ios/scripts/make-digit-templates.swift
//   /tmp/make-digit-templates "/Applications/MuseScore 4.app/Contents/Resources/fonts" \
//       > ios/Mellophone/Import/RasterDigitTemplates.swift
import CoreGraphics
import CoreText
import Foundation

let columns = 10, rows = 14
// OFL faces with SMuFL time signature digits at U+E080 to U+E089. Finale
// Maestro is the face of the ePrint in #49 but ships under an EULA and has no
// such digits, so it is not here.
let faces = ["Leland.otf", "BravuraText.otf", "GootvilleText.otf", "MScoreText.otf", "PetalumaText.otf", "MuseJazzText.otf",
             "LelandText.otf", "Edwin-Roman.otf", "Edwin-Bold.otf", "Edwin-Italic.otf", "Edwin-BdIta.otf", "Campania.otf"]

func grid(of font: CTFont, scalar: UInt32) -> (cells: [Int], aspect: Double)? {
    let size = 200
    var chars = [UniChar(scalar)]
    var glyph = CGGlyph(0)
    guard CTFontGetGlyphsForCharacters(font, &chars, &glyph, 1), glyph != 0 else { return nil }
    var pixels = [UInt8](repeating: 0, count: size * size)
    pixels.withUnsafeMutableBytes { bytes in
        let context = CGContext(data: bytes.baseAddress, width: size, height: size, bitsPerComponent: 8, bytesPerRow: size,
                                space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue)!
        context.setFillColor(gray: 1, alpha: 1)
        var position = CGPoint(x: 40, y: 60)
        CTFontDrawGlyphs(font, &glyph, &position, 1, context)
    }
    var x0 = size, y0 = size, x1 = -1, y1 = -1
    for y in 0..<size { for x in 0..<size where pixels[y * size + x] > 127 {
        x0 = min(x0, x); x1 = max(x1, x); y0 = min(y0, y); y1 = max(y1, y)
    } }
    guard x1 >= x0 else { return nil }
    let w = Double(x1 - x0 + 1), h = Double(y1 - y0 + 1)
    var cells: [Int] = []
    for r in 0..<rows { for c in 0..<columns {
        let xa = x0 + Int(Double(c) * w / Double(columns)), xb = max(x0 + Int(Double(c + 1) * w / Double(columns)) - 1, xa)
        let ya = y0 + Int(Double(r) * h / Double(rows)), yb = max(y0 + Int(Double(r + 1) * h / Double(rows)) - 1, ya)
        var ink = 0, total = 0
        for y in ya...yb { for x in xa...xb { total += 1; if pixels[y * size + x] > 127 { ink += 1 } } }
        cells.append(Int((Double(ink) / Double(total) * 255).rounded()))
    } }
    return (cells, w / h)
}

let directory = CommandLine.arguments[1]
var lines: [String] = []
for face in faces {
    let url = URL(fileURLWithPath: directory).appendingPathComponent(face)
    guard let descriptors = CTFontManagerCreateFontDescriptorsFromURL(url as CFURL) as? [CTFontDescriptor],
          let descriptor = descriptors.first else { FileHandle.standardError.write("missing \(face)\n".data(using: .utf8)!); continue }
    let font = CTFontCreateWithFontDescriptor(descriptor, 140, nil)
    // Time signature digits, then tuplet digits (italic), where a face has them.
    for (base, kind) in [(UInt32(0xE080), "time"), (UInt32(0xE880), "tuplet"), (UInt32(0x30), "text")] { for digit in 0...9 {
        guard let g = grid(of: font, scalar: base + UInt32(digit)) else { continue }
        lines.append("        .init(digit: \(digit), face: \"\(face.replacingOccurrences(of: ".otf", with: ""))\", aspect: \(String(format: "%.4f", g.aspect)), cells: [\(g.cells.map(String.init).joined(separator: ","))]), // \(kind)")
    } }
}
print("""
// Generated by ios/scripts/make-digit-templates.swift. Do not edit by hand.
//
// The time signature digits of the SIL Open Font License music fonts that
// MuseScore 4 installs, as \(columns) x \(rows) grids of ink share (0 to 255).
// DigitReader matches an engraved digit against these (#49).

enum DigitTemplates {
    struct Entry {
        let digit: Int
        let face: String
        let aspect: Double
        let cells: [UInt8]
    }

    static let all: [Entry] = [
\(lines.joined(separator: "\n"))
    ]
}
""")
